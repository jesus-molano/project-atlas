import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const repositoryRoot = process.cwd();
const outputPath = path.join(repositoryRoot, "docs", "generated-quality-summary.md");
const coreProfilePath = path.join(
  repositoryRoot,
  "packages",
  "mcp",
  "core-profile.json",
);
const ignoredDirectories = new Set([
  ".cache",
  ".component-atlas",
  ".git",
  ".nuxt",
  ".output",
  "coverage",
  "dist",
  "node_modules",
]);

async function collect(directory, predicate, results = []) {
  const entries = await readdir(directory, { withFileTypes: true });
  for (const entry of entries) {
    if (entry.isDirectory() && ignoredDirectories.has(entry.name)) {
      continue;
    }
    const absolutePath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      await collect(absolutePath, predicate, results);
    } else if (predicate(absolutePath)) {
      results.push(absolutePath);
    }
  }
  return results;
}

const [
  testFiles,
  vueViews,
  packageDirectories,
  mcpSourceFiles,
  coreProfileSource,
] = await Promise.all([
  collect(repositoryRoot, (file) => /\.(?:test|spec)\.[cm]?[jt]sx?$/u.test(file)),
  collect(
    path.join(repositoryRoot, "apps", "viewer", "app"),
    (file) => file.endsWith(".vue"),
  ),
  readdir(path.join(repositoryRoot, "packages"), { withFileTypes: true }),
  collect(
    path.join(repositoryRoot, "packages", "mcp", "src"),
    (file) =>
      file.endsWith(".ts")
      && !/\.(?:test|spec)\.ts$/u.test(file),
  ),
  readFile(coreProfilePath, "utf8"),
]);

const mcpSources = await Promise.all(
  mcpSourceFiles.map(async (file) => ({ file, source: await readFile(file, "utf8") })),
);
const coreProfile = JSON.parse(coreProfileSource);
if (
  coreProfile.profile !== "core"
  || !Array.isArray(coreProfile.tools)
  || coreProfile.tools.length === 0
  || coreProfile.tools.some(
    (tool) => typeof tool !== "string" || !tool.startsWith("atlas_"),
  )
  || new Set(coreProfile.tools).size !== coreProfile.tools.length
) {
  throw new Error(
    `${path.relative(repositoryRoot, coreProfilePath)} is not a valid core profile contract.`,
  );
}
const coreTools = coreProfile.tools;
const legacySource = mcpSources
  .filter(({ file }) => !file.endsWith(`${path.sep}core-tools.ts`))
  .map(({ source }) => source)
  .join("\n");
const legacyTools = [...legacySource.matchAll(/server\.tool\(\s*"([^"]+)"/gu)]
  .map((match) => match[1])
  .sort();
const packageCount = (
  await Promise.all(
    packageDirectories
      .filter((entry) => entry.isDirectory())
      .map((entry) =>
        readFile(path.join(repositoryRoot, "packages", entry.name, "package.json"), "utf8")
          .then(() => true)
          .catch(() => false),
      ),
  )
).filter(Boolean).length;
const generatedAt = "Generated deterministically from the current checkout.";
const content = `<!-- Generated by scripts/generate-quality-summary.mjs. Do not edit manually. -->
# Project Atlas quality summary

${generatedAt}

| Surface | Current checkout |
| --- | ---: |
| Workspace packages | ${packageCount} |
| Test/spec files | ${testFiles.length} |
| Viewer Vue files included by self-scan | ${vueViews.length} |
| MCP core tools (default) | ${coreTools.length} |
| MCP legacy tools (temporary compatibility profile) | ${legacyTools.length} |

The authoritative pass/fail evidence comes from CI: lint, CSS lint, typecheck,
artifact and maintainability audits, V8 coverage, package/viewer builds, the
complete Vitest suite, and Playwright smoke flows. Historical audit documents
remain dated records and must not be used as current counts.

The default MCP tool count comes from \`packages/mcp/core-profile.json\`; the
test suite requires the live core server and the real \`project-atlas mcp\` CLI
to expose that exact ordered contract.
`;

function normalizeLineEndings(value) {
  return value.replace(/\r\n?/gu, "\n");
}

if (process.argv.includes("--check")) {
  const existing = await readFile(outputPath, "utf8").catch(() => "");
  if (normalizeLineEndings(existing) !== normalizeLineEndings(content)) {
    throw new Error(
      "docs/generated-quality-summary.md is stale. Run pnpm generate:summary.",
    );
  }
  console.log("Generated quality summary is current.");
} else {
  await writeFile(outputPath, content, "utf8");
  console.log(`Wrote ${path.relative(repositoryRoot, outputPath)}.`);
}
