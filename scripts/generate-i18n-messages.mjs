import { writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const target = path.join(
  process.cwd(),
  "apps",
  "viewer",
  "app",
  "i18n",
  "messages.ts",
);
const content = `// Generated by scripts/generate-i18n-messages.mjs. Do not edit directly.
import { SPANISH_FOUNDATION_MESSAGES } from "./messages-foundation";
import { SPANISH_EVIDENCE_MESSAGES } from "./messages-evidence";

export type AtlasLocale = "en" | "es";

export const SPANISH_UI_MESSAGES: Readonly<Record<string, string>> = {
  ...SPANISH_FOUNDATION_MESSAGES,
  ...SPANISH_EVIDENCE_MESSAGES,
};
`;

await writeFile(target, content, "utf8");
console.log(`Generated ${path.relative(process.cwd(), target)}.`);
