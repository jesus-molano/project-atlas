export type MemoryMessageKey = keyof typeof en;

export function memoryText(
  locale: AtlasLocale,
  key: MemoryMessageKey,
  variables: Record<string, string | number> = {},
): string {
  let value: string = messages[locale][key];
  for (const [name, replacement] of Object.entries(variables)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

export function memoryEnumLabel(
  locale: AtlasLocale,
  value: string | undefined,
): string {
  if (!value) return "—";
  return (
    enumLabels[locale][value] ??
    value.replaceAll("_", " ").replaceAll("-", " ")
  );
}

function parsedDate(value: string | undefined): Date | undefined {
  if (!value) return undefined;
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? undefined : date;
}

export function formatMemoryDate(
  locale: AtlasLocale,
  value: string | undefined,
): string | undefined {
  const date = parsedDate(value);
  return date
    ? new Intl.DateTimeFormat(locale === "es" ? "es-ES" : "en-US", {
        dateStyle: "medium",
      }).format(date)
    : value;
}

export function formatMemoryDateTime(
  locale: AtlasLocale,
  value: string | undefined,
): string | undefined {
  const date = parsedDate(value);
  return date
    ? new Intl.DateTimeFormat(locale === "es" ? "es-ES" : "en-US", {
        dateStyle: "medium",
        timeStyle: "short",
      }).format(date)
    : value;
}
